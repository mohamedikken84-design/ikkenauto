-- 016: additive catalogue and detailed specs, never alters or deletes existing dealer data.
-- Automotive suggestions are IKKENAUTO editorial seed values, NOT a licensed mobile.de dataset.
CREATE TABLE IF NOT EXISTS public.portal_vehicle_makes (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name text NOT NULL UNIQUE,
 slug text NOT NULL UNIQUE,
 verified boolean NOT NULL DEFAULT false,
 source_note text NOT NULL DEFAULT 'IKKENAUTO editorial suggestion',
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS public.portal_vehicle_models (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 make_id bigint NOT NULL REFERENCES public.portal_vehicle_makes(id) ON DELETE RESTRICT,
 name text NOT NULL,
 verified boolean NOT NULL DEFAULT false,
 UNIQUE(make_id,name)
);
CREATE INDEX IF NOT EXISTS portal_vehicle_models_make_idx ON public.portal_vehicle_models(make_id);
CREATE TABLE IF NOT EXISTS public.portal_vehicle_generations (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 model_id bigint NOT NULL REFERENCES public.portal_vehicle_models(id) ON DELETE RESTRICT,
 code text NOT NULL,
 year_from integer CHECK (year_from IS NULL OR year_from BETWEEN 1900 AND 2100),
 year_to integer CHECK (year_to IS NULL OR year_to BETWEEN 1900 AND 2100),
 verified boolean NOT NULL DEFAULT false,
 source_url text,
 UNIQUE(model_id,code)
);
CREATE INDEX IF NOT EXISTS portal_generations_model_idx ON public.portal_vehicle_generations(model_id);
CREATE TABLE IF NOT EXISTS public.portal_vehicle_powertrains (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 generation_id bigint NOT NULL REFERENCES public.portal_vehicle_generations(id) ON DELETE RESTRICT,
 name text NOT NULL,
 fuel text,
 power_kw integer CHECK (power_kw IS NULL OR power_kw BETWEEN 1 AND 2000),
 verified boolean NOT NULL DEFAULT false,
 source_url text,
 UNIQUE(generation_id,name)
);
CREATE INDEX IF NOT EXISTS portal_powertrains_generation_idx ON public.portal_vehicle_powertrains(generation_id);
CREATE TABLE IF NOT EXISTS public.portal_vehicle_trims (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 powertrain_id bigint NOT NULL REFERENCES public.portal_vehicle_powertrains(id) ON DELETE RESTRICT,
 name text NOT NULL,
 verified boolean NOT NULL DEFAULT false,
 UNIQUE(powertrain_id,name)
);
CREATE INDEX IF NOT EXISTS portal_trims_powertrain_idx ON public.portal_vehicle_trims(powertrain_id);
CREATE TABLE IF NOT EXISTS public.portal_vehicle_equipment_catalog (
 code text PRIMARY KEY,
 label_nl text NOT NULL,
 category text NOT NULL,
 compatible_fuels text[] NOT NULL DEFAULT '{}',
 enabled boolean NOT NULL DEFAULT true,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS portal_equipment_category_idx ON public.portal_vehicle_equipment_catalog(category);
ALTER TABLE public.portal_vehicles
 ADD COLUMN IF NOT EXISTS vehicle_class text,
 ADD COLUMN IF NOT EXISTS generation_code text,
 ADD COLUMN IF NOT EXISTS motorization text,
 ADD COLUMN IF NOT EXISTS trim_line text,
 ADD COLUMN IF NOT EXISTS catalog_make_id bigint REFERENCES public.portal_vehicle_makes(id) ON DELETE SET NULL,
 ADD COLUMN IF NOT EXISTS catalog_model_id bigint REFERENCES public.portal_vehicle_models(id) ON DELETE SET NULL,
 ADD COLUMN IF NOT EXISTS catalog_generation_id bigint REFERENCES public.portal_vehicle_generations(id) ON DELETE SET NULL,
 ADD COLUMN IF NOT EXISTS catalog_powertrain_id bigint REFERENCES public.portal_vehicle_powertrains(id) ON DELETE SET NULL,
 ADD COLUMN IF NOT EXISTS catalog_trim_id bigint REFERENCES public.portal_vehicle_trims(id) ON DELETE SET NULL,
 ADD COLUMN IF NOT EXISTS specifications jsonb NOT NULL DEFAULT '{}'::jsonb,
 ADD COLUMN IF NOT EXISTS equipment_codes text[] NOT NULL DEFAULT '{}'::text[],
 ADD COLUMN IF NOT EXISTS vat_regime text,
 ADD COLUMN IF NOT EXISTS condition_notes text,
 ADD COLUMN IF NOT EXISTS maintenance_history text,
 ADD COLUMN IF NOT EXISTS accident_history text,
 ADD COLUMN IF NOT EXISTS warranty_months integer;
CREATE INDEX IF NOT EXISTS portal_vehicle_equipment_gin_idx ON public.portal_vehicles USING gin (equipment_codes);
CREATE INDEX IF NOT EXISTS portal_vehicles_dealer_status_latest_idx ON public.portal_vehicles (dealer_id,status,created_at DESC);
CREATE INDEX IF NOT EXISTS portal_vehicles_catalog_model_idx ON public.portal_vehicles (catalog_model_id) WHERE catalog_model_id IS NOT NULL;


